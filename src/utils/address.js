// One-line summary of an address.
export const addressLine = (a) => [a.houseNo, a.street, a.landmark && (/^near\b/i.test(a.landmark) ? a.landmark : `near ${a.landmark}`), a.city, a.state].filter(Boolean).join(', ') + (a.pincode ? ` — ${a.pincode}` : '');
